package reorder

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// fake simulates the tools in memory. failAt makes the n-th changing
// command (counting from 1) fail; calls records what ran.
type fake struct {
	tables map[string][]string // iptables: table -> lines between *table and COMMIT
	nft    []map[string]any    // nft rules of chain inet t c, in order
	ufw    []string
	rules  []prefRule // ip rule, in insertion order
	failAt int
	writes int
	calls  []string
}

func (f *fake) run(_ context.Context, s Step) (string, error) {
	f.calls = append(f.calls, s.String())
	if !s.Check && f.changes(s) {
		f.writes++
		if f.writes == f.failAt {
			return "", errors.New(s.Name + ": injected failure")
		}
	}
	switch s.Name {
	case "iptables-save":
		return f.iptSave(s.Args), nil
	case "iptables-restore":
		return "", f.iptRestore(s.Args, s.Stdin)
	case "nft":
		return f.nftRun(s.Args, s.Stdin)
	case "ufw":
		return f.ufwRun(s.Args)
	case "ip":
		return f.ipRun(s.Args)
	}
	return "", fmt.Errorf("fake: unknown command %s", s.Name)
}

func (f *fake) changes(s Step) bool {
	switch s.Name {
	case "iptables-restore":
		return true
	case "nft":
		return len(s.Args) > 0 && s.Args[len(s.Args)-1] == "-"
	case "ufw":
		return len(s.Args) > 0 && s.Args[0] != "show"
	case "ip":
		return len(s.Args) > 2 && (s.Args[2] == "add" || s.Args[2] == "del")
	}
	return false
}

func (f *fake) iptSave(args []string) string {
	only := ""
	if len(args) == 3 {
		only = args[2]
	}
	names := make([]string, 0, len(f.tables))
	for t := range f.tables {
		names = append(names, t)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, t := range names {
		if only != "" && t != only {
			continue
		}
		b.WriteString("# Generated by fake\n*" + t + "\n")
		for _, l := range f.tables[t] {
			b.WriteString(l + "\n")
		}
		b.WriteString("COMMIT\n# Completed\n")
	}
	return b.String()
}

func (f *fake) iptRestore(args []string, in string) error {
	test := len(args) > 0 && args[0] == "--test"
	parsed := map[string][]string{}
	table := ""
	chains := map[string]bool{}
	for _, l := range strings.Split(strings.TrimSuffix(in, "\n"), "\n") {
		switch {
		case strings.HasPrefix(l, "*"):
			table = l[1:]
			chains = map[string]bool{}
		case l == "COMMIT":
			table = ""
		case table == "":
			return fmt.Errorf("iptables-restore: line outside a table: %q", l)
		case strings.HasPrefix(l, ":"):
			name, _, _ := strings.Cut(l[1:], " ")
			chains[name] = true
			parsed[table] = append(parsed[table], l)
		default:
			rule := counterPrefix.ReplaceAllString(l, "")
			f := strings.Fields(rule)
			if len(f) < 2 || f[0] != "-A" || !chains[f[1]] {
				return fmt.Errorf("iptables-restore: bad line %q", l)
			}
			parsed[table] = append(parsed[table], l)
		}
	}
	if !test {
		for t, ls := range parsed {
			f.tables[t] = ls
		}
	}
	return nil
}

func (f *fake) nftRun(args []string, in string) (string, error) {
	j := strings.Join(args, " ")
	switch {
	case j == "-j list chains":
		return `{"nftables":[{"metainfo":{}},{"chain":{"family":"inet","table":"t","name":"c","handle":1}}]}`, nil
	case j == "-j list chain inet t c":
		objs := []any{map[string]any{"chain": map[string]any{"family": "inet", "table": "t", "name": "c"}}}
		for i, r := range f.nft {
			c := map[string]any{}
			for k, v := range r {
				c[k] = v
			}
			c["handle"] = i + 10
			objs = append(objs, map[string]any{"rule": c})
		}
		b, _ := json.Marshal(map[string]any{"nftables": objs})
		return string(b), nil
	case j == "-a list chain inet t c":
		var b strings.Builder
		b.WriteString("table inet t {\n\tchain c { # handle 1\n")
		for i, r := range f.nft {
			fmt.Fprintf(&b, "\t\t%s # handle %d\n", r["comment"], i+10)
		}
		b.WriteString("\t}\n}\n")
		return b.String(), nil
	case strings.HasSuffix(j, "-j -f -"):
		var doc struct {
			Nftables []map[string]map[string]json.RawMessage `json:"nftables"`
		}
		if err := json.Unmarshal([]byte(in), &doc); err != nil {
			return "", err
		}
		next := append([]map[string]any(nil), f.nft...)
		for _, cmd := range doc.Nftables {
			if _, ok := cmd["flush"]; ok {
				next = nil
				continue
			}
			var r map[string]any
			if err := json.Unmarshal(cmd["add"]["rule"], &r); err != nil {
				return "", err
			}
			if _, has := r["handle"]; has {
				return "", errors.New("nft: a rule to add has a handle")
			}
			next = append(next, r)
		}
		if args[0] != "-c" {
			f.nft = next
		}
		return "", nil
	}
	return "", fmt.Errorf("fake nft: %v", args)
}

func ufwJoin(words []string) string {
	for i, w := range words {
		if strings.ContainsAny(w, " ") {
			words[i] = "'" + w + "'"
		}
	}
	return strings.Join(words, " ")
}

func (f *fake) ufwRun(args []string) (string, error) {
	switch {
	case len(args) == 2 && args[0] == "show":
		if len(f.ufw) == 0 {
			return "Added user rules (see 'ufw status' for running firewall):\n(None)\n", nil
		}
		return "Added user rules (see 'ufw status' for running firewall):\nufw " + strings.Join(f.ufw, "\nufw ") + "\n", nil
	case args[0] == "--force":
		var spec string
		if args[1] == "route" {
			spec = ufwJoin(append([]string{"route"}, args[3:]...))
		} else {
			spec = ufwJoin(append([]string(nil), args[2:]...))
		}
		for i, s := range f.ufw {
			if s == spec {
				f.ufw = append(f.ufw[:i], f.ufw[i+1:]...)
				return "Rule deleted\n", nil
			}
		}
		return "", errors.New("Could not delete non-existent rule")
	default:
		spec := ufwJoin(append([]string(nil), args...))
		for _, s := range f.ufw {
			if s == spec {
				return "Skipping adding existing rule\n", nil
			}
		}
		f.ufw = append(f.ufw, spec)
		return "Rule added\n", nil
	}
}

func (f *fake) ipRun(args []string) (string, error) {
	switch {
	case len(args) == 3 && args[2] == "show":
		sorted := append([]prefRule(nil), f.rules...)
		sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].pref < sorted[j].pref })
		var b strings.Builder
		for _, r := range sorted {
			fmt.Fprintf(&b, "%d:\t%s\n", r.pref, r.text)
		}
		return b.String(), nil
	case len(args) > 4 && args[3] == "pref":
		p, _ := strconv.Atoi(args[4])
		pr := prefRule{p, strings.Join(args[5:], " ")}
		if args[2] == "add" {
			f.rules = append(f.rules, pr)
			return "", nil
		}
		for i, r := range f.rules {
			if r == pr {
				f.rules = append(f.rules[:i], f.rules[i+1:]...)
				return "", nil
			}
		}
		return "", errors.New("RTNETLINK answers: No such file or directory")
	}
	return "", fmt.Errorf("fake ip: %v", args)
}
